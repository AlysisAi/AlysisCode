"""Common Bots schema; dialect differences are explicit DDL types."""

# 39 fences older workers whose reconciliation deletes every retained VM.
# Sleeping allocation records must never be opened by those workers.
SCHEMA_VERSION = 39


def schema(*, postgres=False):
    return _DDL.format(
        sequence="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if postgres
        else "INTEGER PRIMARY KEY AUTOINCREMENT",
        real="DOUBLE PRECISION" if postgres else "REAL",
        blob="BYTEA" if postgres else "BLOB",
        rowid="rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE," if postgres else "",
    )


_DDL = """
                CREATE TABLE IF NOT EXISTS cloud_accounts (
                    owner TEXT PRIMARY KEY, credential TEXT NOT NULL,
                    updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS host_maintenance (
                    id INTEGER PRIMARY KEY CHECK(id=1), token TEXT NOT NULL,
                    expires_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bots (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
                    purpose TEXT NOT NULL, instructions TEXT NOT NULL,
                    memory_enabled INTEGER NOT NULL, files_enabled INTEGER NOT NULL,
                    created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS bots_owner ON bots(owner);
                CREATE TABLE IF NOT EXISTS bot_reply_review_settings (
                    owner TEXT PRIMARY KEY,
                    enabled INTEGER NOT NULL CHECK(enabled IN (0,1))
                );
                CREATE TABLE IF NOT EXISTS bot_review_settings (
                    bot_id TEXT PRIMARY KEY REFERENCES bots(id), mode TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_action_rules (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    effect TEXT NOT NULL CHECK(effect IN ('allow','ask')),
                    description TEXT NOT NULL, action TEXT,
                    source_review_id TEXT UNIQUE, revision INTEGER NOT NULL,
                    deleted INTEGER NOT NULL DEFAULT 0,
                    created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS bot_action_rules_bot ON bot_action_rules(bot_id,deleted);
                CREATE TABLE IF NOT EXISTS chats (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    title TEXT NOT NULL, created_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS tasks (
                    id TEXT PRIMARY KEY, chat_id TEXT NOT NULL REFERENCES chats(id),
                    bot_id TEXT NOT NULL REFERENCES bots(id), owner TEXT NOT NULL,
                    request_id TEXT NOT NULL, message TEXT NOT NULL, status TEXT NOT NULL,
                    config TEXT NOT NULL, created_at {real} NOT NULL, updated_at {real} NOT NULL,
                    error TEXT, calls INTEGER NOT NULL DEFAULT 0, output TEXT NOT NULL DEFAULT '',
                    UNIQUE(owner, request_id)
                );
                CREATE TABLE IF NOT EXISTS bot_local_devices (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
                    platform TEXT NOT NULL, session_id TEXT NOT NULL,
                    connected INTEGER NOT NULL, seen {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_local_requests (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    task_id TEXT NOT NULL REFERENCES tasks(id), device_id TEXT NOT NULL REFERENCES bot_local_devices(id),
                    kind TEXT NOT NULL, arguments TEXT NOT NULL, generation TEXT NOT NULL,
                    status TEXT NOT NULL, session_id TEXT, result TEXT, created_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS bot_local_requests_device ON bot_local_requests(device_id,status);
                CREATE TABLE IF NOT EXISTS bot_local_device_grants (
                    token_hash TEXT PRIMARY KEY, device_id TEXT NOT NULL REFERENCES bot_local_devices(id),
                    owner TEXT NOT NULL, revoked INTEGER NOT NULL, created_at {real} NOT NULL
                );
                CREATE UNIQUE INDEX IF NOT EXISTS bot_local_active_grant
                    ON bot_local_device_grants(device_id) WHERE revoked=0;
                CREATE TABLE IF NOT EXISTS bot_local_admissions (
                    request_id TEXT PRIMARY KEY REFERENCES bot_local_requests(id),
                    token_hash TEXT NOT NULL REFERENCES bot_local_device_grants(token_hash)
                );
                CREATE TABLE IF NOT EXISTS bot_computer_control (
                    bot_id TEXT PRIMARY KEY REFERENCES bots(id),
                    task_id TEXT REFERENCES tasks(id), session_id TEXT NOT NULL,
                    state TEXT NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_action_reviews (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    task_id TEXT NOT NULL REFERENCES tasks(id), action TEXT NOT NULL,
                    generation TEXT NOT NULL, status TEXT NOT NULL, revision INTEGER NOT NULL,
                    created_at {real} NOT NULL, decided_at {real}, reason TEXT NOT NULL DEFAULT ''
                );
                CREATE INDEX IF NOT EXISTS bot_action_reviews_task ON bot_action_reviews(task_id,status);
                CREATE INDEX IF NOT EXISTS tasks_queue ON tasks(status, created_at);
                DROP INDEX IF EXISTS one_active_task_per_chat;
                CREATE UNIQUE INDEX IF NOT EXISTS one_foreground_task_per_chat
                    ON tasks(chat_id) WHERE status IN ('running','cancelling');
                CREATE TABLE IF NOT EXISTS messages ({rowid}
                    id TEXT PRIMARY KEY, chat_id TEXT NOT NULL REFERENCES chats(id),
                    task_id TEXT NOT NULL REFERENCES tasks(id), role TEXT NOT NULL,
                    content TEXT NOT NULL, created_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS events (
                    seq {sequence}, task_id TEXT NOT NULL REFERENCES tasks(id),
                    kind TEXT NOT NULL, data TEXT NOT NULL, created_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS memories (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    title TEXT NOT NULL, content TEXT NOT NULL, status TEXT NOT NULL,
                    source_task_id TEXT REFERENCES tasks(id), created_at {real} NOT NULL,
                    updated_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS memories_bot ON memories(bot_id);
                CREATE TABLE IF NOT EXISTS memory_applicability (
                    memory_id TEXT PRIMARY KEY REFERENCES memories(id) ON DELETE CASCADE,
                    source_hash TEXT NOT NULL, scope TEXT NOT NULL CHECK(scope IN ('general','contextual'))
                );
                CREATE TABLE IF NOT EXISTS files (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    name TEXT NOT NULL, content TEXT NOT NULL, source_task_id TEXT REFERENCES tasks(id),
                    created_at {real} NOT NULL, updated_at {real} NOT NULL,
                    series_id TEXT NOT NULL, revision INTEGER NOT NULL, UNIQUE(bot_id,name,revision)
                );
                CREATE TABLE IF NOT EXISTS file_payloads ({rowid}
                    file_id TEXT PRIMARY KEY REFERENCES files(id) ON DELETE CASCADE,
                    data {blob} NOT NULL, media_type TEXT NOT NULL, sha256 TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS files_bot_recent ON files(bot_id,created_at DESC,id DESC);
                CREATE INDEX IF NOT EXISTS files_task_recent ON files(bot_id,source_task_id,created_at DESC,id DESC);
                CREATE TABLE IF NOT EXISTS file_uploads ({rowid}
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    name TEXT NOT NULL, size INTEGER NOT NULL, received INTEGER NOT NULL,
                    status TEXT NOT NULL, expires {real} NOT NULL, request_id TEXT NOT NULL,
                    file_id TEXT, data {blob}, previous_file_id TEXT, UNIQUE(bot_id, request_id)
                );
                CREATE TABLE IF NOT EXISTS clarifications (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    source_task_id TEXT NOT NULL UNIQUE REFERENCES tasks(id), question TEXT NOT NULL,
                    options TEXT NOT NULL, status TEXT NOT NULL, revision INTEGER NOT NULL,
                    answer TEXT, answer_task_id TEXT REFERENCES tasks(id),
                    delivered_to_source INTEGER NOT NULL, created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS clarifications_bot ON clarifications(bot_id,status);
                CREATE TABLE IF NOT EXISTS browser_task_drafts (
                    task_id TEXT PRIMARY KEY REFERENCES tasks(id) ON DELETE CASCADE,
                    content TEXT NOT NULL, captured_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS provider_calls (
                    id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id),
                    model TEXT NOT NULL, status TEXT NOT NULL, usage TEXT,
                    created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS working_notes (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    title TEXT NOT NULL, content TEXT NOT NULL, revision INTEGER NOT NULL,
                    source_task_id TEXT REFERENCES tasks(id), created_at {real} NOT NULL,
                    updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS memory_replacements (
                    proposal_id TEXT PRIMARY KEY REFERENCES memories(id) ON DELETE CASCADE,
                    target_id TEXT NOT NULL, expected_updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS memory_changes (
                    seq {sequence}, bot_id TEXT NOT NULL REFERENCES bots(id),
                    memory_id TEXT NOT NULL, action TEXT NOT NULL,
                    previous_status TEXT, status TEXT NOT NULL,
                    source_task_id TEXT, related_memory_id TEXT, created_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS memory_changes_bot ON memory_changes(bot_id,seq);
                CREATE TABLE IF NOT EXISTS note_revisions (
                    note_id TEXT NOT NULL REFERENCES working_notes(id), revision INTEGER NOT NULL,
                    title TEXT NOT NULL, content TEXT NOT NULL,
                    source_task_id TEXT REFERENCES tasks(id), created_at {real} NOT NULL,
                    PRIMARY KEY(note_id,revision)
                );
                CREATE TABLE IF NOT EXISTS note_consolidations (
                    seq {sequence}, source_note_id TEXT NOT NULL REFERENCES working_notes(id),
                    source_revision INTEGER NOT NULL,
                    target_note_id TEXT NOT NULL REFERENCES working_notes(id),
                    target_revision INTEGER NOT NULL,
                    reason TEXT NOT NULL, source_task_id TEXT REFERENCES tasks(id),
                    created_at {real} NOT NULL, restored_at {real}
                );
                CREATE UNIQUE INDEX IF NOT EXISTS note_archive_active
                    ON note_consolidations(source_note_id) WHERE restored_at IS NULL;
                CREATE INDEX IF NOT EXISTS note_consolidation_target
                    ON note_consolidations(target_note_id);
                CREATE INDEX IF NOT EXISTS notes_bot ON working_notes(bot_id);
                CREATE INDEX IF NOT EXISTS chats_bot ON chats(bot_id);
                CREATE INDEX IF NOT EXISTS messages_chat ON messages(chat_id);
                CREATE INDEX IF NOT EXISTS messages_task_source ON messages(task_id,role,created_at,id);
                CREATE INDEX IF NOT EXISTS messages_chat_reply ON messages(chat_id,role,created_at,id);
                CREATE TABLE IF NOT EXISTS schedules (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    name TEXT NOT NULL, prompt TEXT NOT NULL, timing TEXT NOT NULL,
                    state TEXT NOT NULL, revision INTEGER NOT NULL, next_run_at {real},
                    pause_reason TEXT, source_task_id TEXT REFERENCES tasks(id),
                    created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS schedule_requests (
                    bot_id TEXT NOT NULL REFERENCES bots(id), request_id TEXT NOT NULL,
                    schedule_id TEXT NOT NULL REFERENCES schedules(id), payload TEXT NOT NULL,
                    PRIMARY KEY(bot_id, request_id)
                );
                CREATE INDEX IF NOT EXISTS schedules_due ON schedules(state,next_run_at);
                CREATE TABLE IF NOT EXISTS schedule_runs (
                    id {sequence},
                    schedule_id TEXT NOT NULL REFERENCES schedules(id),
                    schedule_revision INTEGER NOT NULL, scheduled_for {real} NOT NULL,
                    task_id TEXT REFERENCES tasks(id), status TEXT NOT NULL,
                    reason TEXT, config TEXT NOT NULL, created_at {real} NOT NULL,
                    UNIQUE(schedule_id,scheduled_for)
                );
                CREATE INDEX IF NOT EXISTS schedule_runs_task ON schedule_runs(task_id);
                CREATE TABLE IF NOT EXISTS chat_read_cursors (
                    chat_id TEXT PRIMARY KEY REFERENCES chats(id), event_seq INTEGER NOT NULL
                );
                CREATE INDEX IF NOT EXISTS events_task ON events(task_id,seq);
                CREATE TABLE IF NOT EXISTS coding_workspaces (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
                    worker_id TEXT NOT NULL, heartbeat {real} NOT NULL,
                    bot_id TEXT UNIQUE REFERENCES bots(id), session_id TEXT
                );
                CREATE TABLE IF NOT EXISTS coding_jobs (
                    id TEXT PRIMARY KEY, task_id TEXT NOT NULL UNIQUE REFERENCES tasks(id),
                    workspace_id TEXT NOT NULL REFERENCES coding_workspaces(id),
                    session_id TEXT NOT NULL, worker_id TEXT,
                    status TEXT NOT NULL, context TEXT NOT NULL, result TEXT,
                    created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS coding_calls (
                    job_id TEXT NOT NULL REFERENCES coding_jobs(id), request_id TEXT NOT NULL,
                    phase TEXT NOT NULL, request_hash TEXT NOT NULL, call_id TEXT NOT NULL UNIQUE REFERENCES provider_calls(id),
                    response TEXT, PRIMARY KEY(job_id,request_id)
                );
                CREATE TABLE IF NOT EXISTS task_waits (
                    task_id TEXT PRIMARY KEY REFERENCES tasks(id), continuation TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS coding_instructions (
                    job_id TEXT NOT NULL REFERENCES coding_jobs(id), revision INTEGER NOT NULL,
                    source_task_id TEXT NOT NULL REFERENCES tasks(id), content TEXT NOT NULL,
                    created_at {real} NOT NULL, PRIMARY KEY(job_id,revision), UNIQUE(job_id,source_task_id)
                );
                CREATE TABLE IF NOT EXISTS action_proposals (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    source_task_id TEXT NOT NULL UNIQUE REFERENCES tasks(id), anchor_task_id TEXT REFERENCES tasks(id),
                    question TEXT NOT NULL, instructions TEXT NOT NULL, status TEXT NOT NULL,
                    revision INTEGER NOT NULL, bot_updated_at {real} NOT NULL, visible_after {real} NOT NULL,
                    task_id TEXT REFERENCES tasks(id), created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_triggers (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    name TEXT NOT NULL, kind TEXT NOT NULL, instructions TEXT NOT NULL,
                    state TEXT NOT NULL, revision INTEGER NOT NULL,
                    source_task_id TEXT UNIQUE REFERENCES tasks(id), bot_updated_at {real} NOT NULL,
                    last_run_at {real}, created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS activation_events (
                    id TEXT PRIMARY KEY, bot_id TEXT NOT NULL REFERENCES bots(id),
                    kind TEXT NOT NULL, resource_id TEXT NOT NULL, payload TEXT NOT NULL,
                    created_at {real} NOT NULL, UNIQUE(bot_id,kind,resource_id)
                );
                CREATE TABLE IF NOT EXISTS trigger_deliveries (
                    id TEXT PRIMARY KEY, trigger_id TEXT NOT NULL REFERENCES bot_triggers(id),
                    trigger_revision INTEGER NOT NULL, event_id TEXT NOT NULL REFERENCES activation_events(id),
                    task_id TEXT REFERENCES tasks(id), state TEXT NOT NULL, reason TEXT, created_at {real} NOT NULL,
                    UNIQUE(trigger_id,event_id)
                );
                CREATE INDEX IF NOT EXISTS trigger_delivery_tasks ON trigger_deliveries(task_id);
                CREATE INDEX IF NOT EXISTS trigger_delivery_pending ON trigger_deliveries(trigger_id,state);
                CREATE TABLE IF NOT EXISTS background_turns (
                    task_id TEXT PRIMARY KEY REFERENCES tasks(id), state TEXT NOT NULL,
                    summary TEXT NOT NULL, messages TEXT NOT NULL, applied_seq INTEGER NOT NULL
                );
                CREATE TABLE IF NOT EXISTS background_instructions (
                    seq {sequence}, task_id TEXT NOT NULL REFERENCES background_turns(task_id),
                    source_task_id TEXT NOT NULL REFERENCES tasks(id), content TEXT NOT NULL,
                    UNIQUE(task_id,source_task_id)
                );
                CREATE TABLE IF NOT EXISTS peer_exchanges (
                    id TEXT PRIMARY KEY, source_task_id TEXT NOT NULL UNIQUE REFERENCES tasks(id),
                    source_bot_id TEXT NOT NULL REFERENCES bots(id), recipient_bot_id TEXT NOT NULL,
                    source_name TEXT NOT NULL, recipient_name TEXT NOT NULL, brief TEXT NOT NULL,
                    shared_files TEXT NOT NULL, corrections TEXT NOT NULL, continuation TEXT NOT NULL,
                    status TEXT NOT NULL, revision INTEGER NOT NULL, calls INTEGER NOT NULL,
                    call_limit INTEGER NOT NULL, result TEXT NOT NULL DEFAULT '', error TEXT,
                    reported_at {real}, created_at {real} NOT NULL, updated_at {real} NOT NULL
                );
                CREATE TABLE IF NOT EXISTS peer_calls (
                    exchange_id TEXT NOT NULL REFERENCES peer_exchanges(id),
                    call_id TEXT PRIMARY KEY REFERENCES provider_calls(id), revision INTEGER NOT NULL
                );
                CREATE INDEX IF NOT EXISTS peer_queue ON peer_exchanges(status,created_at);
                CREATE TABLE IF NOT EXISTS bot_context_summaries (
                    bot_id TEXT PRIMARY KEY REFERENCES bots(id), revision INTEGER NOT NULL,
                    memory_version TEXT NOT NULL, through_time {real} NOT NULL,
                    through_id TEXT NOT NULL, content TEXT NOT NULL,
                    attempt_key TEXT, updated_at {real} NOT NULL
                );


                CREATE TABLE IF NOT EXISTS file_objects (
                    file_id TEXT PRIMARY KEY REFERENCES files(id) ON DELETE CASCADE,
                    ref TEXT NOT NULL, size_bytes INTEGER NOT NULL,
                    "binary" INTEGER NOT NULL, media_type TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS workspace_objects (
                    id TEXT PRIMARY KEY, task_id TEXT REFERENCES tasks(id),
                    bot_id TEXT NOT NULL REFERENCES bots(id),
                    ref TEXT NOT NULL, created_at {real} NOT NULL,
                    settled INTEGER NOT NULL DEFAULT 0 CHECK(settled IN (0,1))
                );
                CREATE INDEX IF NOT EXISTS workspace_objects_bot
                    ON workspace_objects(bot_id,created_at);
                CREATE TABLE IF NOT EXISTS browser_states (
                    id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id),
                    bot_id TEXT NOT NULL REFERENCES bots(id), ref TEXT NOT NULL,
                    created_at {real} NOT NULL,
                    settled INTEGER NOT NULL DEFAULT 0 CHECK(settled IN (0,1))
                );
                CREATE INDEX IF NOT EXISTS browser_states_bot ON browser_states(bot_id,created_at);
                CREATE TABLE IF NOT EXISTS stored_objects (
                    key TEXT PRIMARY KEY, owner TEXT NOT NULL, bot_id TEXT NOT NULL,
                    ref TEXT NOT NULL, state TEXT NOT NULL,
                    created_at {real} NOT NULL, unreferenced_at {real}, checked_at {real} NOT NULL
                );
                CREATE INDEX IF NOT EXISTS stored_objects_cleanup
                    ON stored_objects(owner,state,checked_at);
                CREATE TABLE IF NOT EXISTS object_storage_enabled (id INTEGER PRIMARY KEY);

CREATE TABLE IF NOT EXISTS task_tool_results (
 id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id),
 tool_name TEXT NOT NULL, content TEXT NOT NULL, created_at {real} NOT NULL
);
CREATE INDEX IF NOT EXISTS task_tool_results_task ON task_tool_results(task_id);
CREATE TABLE IF NOT EXISTS worker_leases (
 owner TEXT PRIMARY KEY, worker_id TEXT NOT NULL, epoch INTEGER NOT NULL,
 expires {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS computer_allocations (
 owner TEXT NOT NULL, bot_id TEXT NOT NULL REFERENCES bots(id),
 record TEXT NOT NULL, updated_at {real} NOT NULL, PRIMARY KEY(owner,bot_id)
);
CREATE TABLE IF NOT EXISTS library_allowances (
 owner TEXT PRIMARY KEY, byte_limit BIGINT CHECK(byte_limit >= 0), updated_at {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS library_reservations (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, bot_id TEXT NOT NULL REFERENCES bots(id),
 size_bytes BIGINT NOT NULL CHECK(size_bytes >= 0), expires {real} NOT NULL
);
CREATE INDEX IF NOT EXISTS library_reservations_owner ON library_reservations(owner,expires);
CREATE TABLE IF NOT EXISTS computer_capacity (
 scope TEXT PRIMARY KEY, max_active INTEGER CHECK(max_active > 0)
);
"""
